"""Regenerate docs/AWS_LIVE_TEST_RESULTS.md from the raw live-test outputs (no hand-edited results).
Usage: python docs/evidence/capture/make_live_results.py
"""

import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[3]
T = ROOT / "docs" / "evidence" / "09_testing"
api = json.loads((T / "live_api_results.json").read_text(encoding="utf-8"))
ui = json.loads((T / "live_browser_results.json").read_text(encoding="utf-8"))
local = (T / "final_local_regression.txt").read_text(encoding="utf-8")


def esc(s) -> str:
    return str(s).replace("|", "\\|").replace("\n", " ")


lim = api.get("limitations", 0)
failed = api["total"] - api["passed"] - lim
ui_pass = sum(c["status"] == "PASS" for c in ui["checks"])
L = [
    "# FinSight — AWS Live Test Results", "",
    "Executed against the deployed stack `finance-intelligence-prod` (ap-south-1, account `9672****3724`).",
    "Only synthetic data and synthetic test users were used. Generated by `docs/evidence/capture/make_live_results.py` from the",
    "raw outputs in `docs/evidence/09_testing/` (`live_api_results.json`, `live_browser_results.json`, `live_api_test_console.txt`,",
    "`final_local_regression.txt`). Test scripts: `infra/live_test.py` (API, Cognito, S3, OCR) and `docs/evidence/capture/live.mjs`",
    "(real headless Chrome against the live site).", "",
    "## Summary", "",
    "| Suite | Result |", "|---|---|",
    f"| Live API / Cognito / S3 / OCR (run {api['ran_at'][:16]}) | **{api['passed']} passed, {lim} limitation(s), {failed} failed** of {api['total']} |",
    f"| Live browser (run {ui['ranAt'][:16]}Z) | **{ui_pass}/{len(ui['checks'])} passed**, {len(ui['consoleErrors'])} console errors, {len(ui['failedRequests'])} failed requests |",
    "| Local regression (latest code) | " + " · ".join(l.strip() for l in local.splitlines() if any(k in l for k in ("passed", "exit=", "built in", "Tests"))) + " |",
    "", "Live URL: `https://zkht2b4ib3.execute-api.ap-south-1.amazonaws.com` (SPA and API on one origin via API Gateway + Lambda;",
    "CloudFront is planned and blocked pending AWS account verification).", "",
    "## Live API, authentication, storage and OCR", "",
    "| ID | Feature | Method | Expected | Actual | Status |", "|---|---|---|---|---|---|",
]
L += [f"| {r['id']} | {esc(r['feature'])} | {esc(r['method'])} | {esc(r['expected'])} | {esc(r['actual'])[:170]} | **{r['status']}** |" for r in api["results"]]
L += ["", "## Live browser checks (real UI on the deployed site)", "", "| ID | Check | Status | Detail |", "|---|---|---|---|"]
L += [f"| {c['id']} | {esc(c['what'])} | **{c['status']}** | {esc(c.get('detail', ''))[:120]} |" for c in ui["checks"]]
L += [
    "", "Screenshots: `docs/evidence/08_live_application/` (index: `docs/evidence/SCREENSHOT_INDEX.md`).", "",
    "## Problems found during live work and their fixes", "",
    "| When | Symptom | Cause | Fix |", "|---|---|---|---|",
    "| Deploy 1–2 | `FrontendDistribution` CREATE_FAILED: *Your account must be verified before you can add new CloudFront resources* | New-account CloudFront restriction (needs AWS Support) | Rollbacks; empty retained table deleted with owner approval; `FrontendHosting=apigateway` (WebFunction serves the SPA on the HTTP API) |",
    "| Deploy 3 | `/health` 500, `Runtime.ImportModuleError … pydantic_core` | SAM's Python builder skips `*.so` when copying source, so vendored native wheels were dropped | Stage `requirements.txt` so aws-lambda-builders fetches manylinux cp313 wheels; verified in a Linux cp313 container |",
    "| Live run 2 | Presigned POST answered **307** | Global S3 endpoint redirects for new buckets outside us-east-1 | S3 client pinned to the regional virtual-hosted endpoint + regression test |",
    "| Session 11 runs | AUTH-07: an access token still worked after GlobalSignOut until expiry (documented limitation) | API Gateway JWT authorizers check signature/expiry only | Session 12: backend checks the token with Cognito `GetUser` (cached 15 s per token, fail-open on throttling with a log line); live AUTH-07 now returns **401 token_revoked** about 17 s after sign-out |",
    "| Harness | console encoding, transient `WinError 10054` resets, fixed sleeps on a slow link | test machine / script | UTF-8 output, transport-error retries, wait for rendered content |",
    "", "## Remaining limitations", "",
    "- Revocation takes effect within the 15 s check cache per warm Lambda container, not instantly. If Cognito throttles or is unreachable, the check is skipped (logged), the request is served, and the token is still valid by signature and expiry.",
    "- Sign-up email confirmation through a real inbox was not exercised. Test users were confirmed with `AdminConfirmSignUp`.",
    "- The CloudFront delivery path is untested until AWS enables CloudFront on the account.",
    "- Cold starts take about 3 s per zip function (512 MB); the OCR container's first start is slower. Warm requests take 15–130 ms (`docs/evidence/10_monitoring/`).",
]
(ROOT / "docs" / "AWS_LIVE_TEST_RESULTS.md").write_text("\n".join(L) + "\n", encoding="utf-8")
print("written", len(L), "lines")
